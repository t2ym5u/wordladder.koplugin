#!/usr/bin/env python3
# Builds accepted_fr.lua: the French 3-5 letter words a player may step
# through besides words_fr.lua. Run from the monorepo root:
#
#   python3 wordladder.koplugin/tools/build_accepted_fr.py
#
# Source: boggle.koplugin/words_fr.lua, both blocks (the CC0 Scrabble-valid
# list, and the Grammalecte lexicon's forms added by
# boggle.koplugin/tools/lexicon_fr.py, filtered for family play there). Kept:
# 3-5 letter words not already in words_fr.lua. words_fr.lua, which the word
# graphs (puzzles, solutions, hints) are built from, is never touched: no
# puzzle changes and no word is ever removed.
import os, re

ROOT = os.path.dirname(os.path.dirname(os.path.realpath(__file__)))
BOGGLE = os.path.join(os.path.dirname(ROOT), "boggle.koplugin")


def words_of(path):
    text = open(path, encoding="utf-8").read()
    return {w.lower() for b in re.findall(r"\[\[(.*?)\]\]", text, re.S) for w in re.findall(r"[A-Za-z]+", b)}


def wrap(words, width=150):
    lines, line = [], ""
    for w in words:
        if line and len(line) + len(w) + 1 > width:
            lines.append(line)
            line = ""
        line += w + ","
    lines.append(line)
    return "\n".join(lines)


def main():
    known = words_of(os.path.join(ROOT, "words_fr.lua"))
    accepted = sorted(w for w in words_of(os.path.join(BOGGLE, "words_fr.lua"))
                      if 3 <= len(w) <= 5 and w not in known)
    with open(os.path.join(ROOT, "accepted_fr.lua"), "w", encoding="utf-8") as f:
        f.write(f"""-- French words a player may step through besides words_fr.lua (3-5 letters)
-- {len(accepted)} words (generated by tools/build_accepted_fr.py, do not edit)
--
-- Never used to build a ladder: see isAccepted() in board.lua. Source:
-- boggle.koplugin/words_fr.lua, i.e. the CC0 Scrabble-valid list and forms of
-- the Grammalecte lexicon v7.7 (Olivier R., Dicollecte, https://grammalecte.net,
-- Mozilla Public License 2.0), minus familiar, pejorative, slang and sexual
-- words; see that file for the full credits.
local W = {{}}
local raw = [[
{wrap(accepted)}
]]
for word in raw:gmatch("%a+") do W[word] = true end
return W
""")
    print("accepted_fr.lua:", len(accepted), "words")


if __name__ == "__main__":
    main()
